-- ESTADISTICAS-MOLSAN: copia independiente del catálogo CTN.
-- No incluir IBAN, hashes de contraseñas ni credenciales de portales.
CREATE TABLE IF NOT EXISTS public.ctn_notarios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo varchar(50),
  nombre varchar(150),
  apellidos varchar(150),
  nif varchar(50),
  telefono varchar(50),
  departamento_cancelaciones text,
  departamento_copias text,
  otros_departamentos text,
  cp varchar(10),
  provincia varchar(100),
  municipio varchar(100),
  vc varchar(50),
  apoderado varchar(150),
  apoderado_s varchar(150),
  observacion text,
  apoderado_id integer,
  direccion varchar(255),
  lat text,
  lng text,
  source_system varchar(40) NOT NULL DEFAULT 'CTN_RENDER',
  source_synced_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.ctn_notarios IS 'Copia estadística del catálogo CTN. Excluye IBAN y credenciales de portales.';
COMMENT ON COLUMN public.ctn_notarios.apoderado_id IS 'Identificador legado del ERP origen; no referencia empleados en este proyecto.';

CREATE INDEX IF NOT EXISTS idx_estad_ctn_codigo ON public.ctn_notarios (codigo);
CREATE INDEX IF NOT EXISTS idx_estad_ctn_nif ON public.ctn_notarios (nif);
CREATE INDEX IF NOT EXISTS idx_estad_ctn_nombre ON public.ctn_notarios (nombre, apellidos);
CREATE INDEX IF NOT EXISTS idx_estad_ctn_provincia_municipio ON public.ctn_notarios (provincia, municipio);
CREATE INDEX IF NOT EXISTS idx_estad_ctn_vc ON public.ctn_notarios (vc);
CREATE INDEX IF NOT EXISTS idx_estad_ctn_apoderado ON public.ctn_notarios (apoderado);

CREATE TABLE IF NOT EXISTS public.ctn_notarios_asociados (
  notario_id integer NOT NULL REFERENCES public.ctn_notarios(id) ON DELETE CASCADE,
  asociado_id integer NOT NULL REFERENCES public.ctn_notarios(id) ON DELETE CASCADE,
  PRIMARY KEY (notario_id, asociado_id),
  CONSTRAINT ctn_no_self_association CHECK (notario_id <> asociado_id)
);
CREATE INDEX IF NOT EXISTS idx_estad_ctn_asociado ON public.ctn_notarios_asociados (asociado_id);

CREATE TABLE IF NOT EXISTS public.ctn_importaciones (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  origen varchar(40) NOT NULL DEFAULT 'CTN_RENDER',
  nombre_fichero text,
  registros_leidos integer NOT NULL DEFAULT 0,
  registros_importados integer NOT NULL DEFAULT 0,
  estado varchar(20) NOT NULL DEFAULT 'completada',
  detalle jsonb NOT NULL DEFAULT '{}'::jsonb,
  importado_en timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_estad_ctn_importaciones_fecha ON public.ctn_importaciones (importado_en DESC);

ALTER TABLE public.ctn_notarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ctn_notarios_asociados ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ctn_importaciones ENABLE ROW LEVEL SECURITY;

GRANT SELECT ON public.ctn_notarios, public.ctn_notarios_asociados, public.ctn_importaciones TO authenticated;
DROP POLICY IF EXISTS authenticated_read_ctn_notarios ON public.ctn_notarios;
CREATE POLICY authenticated_read_ctn_notarios ON public.ctn_notarios FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS authenticated_read_ctn_asociados ON public.ctn_notarios_asociados;
CREATE POLICY authenticated_read_ctn_asociados ON public.ctn_notarios_asociados FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS authenticated_read_ctn_importaciones ON public.ctn_importaciones;
CREATE POLICY authenticated_read_ctn_importaciones ON public.ctn_importaciones FOR SELECT TO authenticated USING (true);
